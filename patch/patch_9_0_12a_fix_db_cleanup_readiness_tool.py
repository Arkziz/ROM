from pathlib import Path
from datetime import datetime
import py_compile

PATCH_NAME = "9_0_12a_fix_db_cleanup_readiness_tool"
TARGET_RELATIVE = Path("tools") / "db_cleanup_readiness.py"

TOOL_CODE = r'''#!/usr/bin/env python3
"""
ROM db.py cleanup readiness report.

Refactor 9.0.12a safety tool.

This tool produces DB_CLEANUP_9_0_12_REPORT.md and shows:
- duplicate top-level definitions in db.py;
- legacy references created by refactor wrappers;
- facade/compatibility markers;
- functions that are likely NOT safe to delete yet because wrappers still depend on legacy refs;
- recommended cleanup order.
"""

from __future__ import annotations

import ast
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / "db.py"
REPORT_PATH = ROOT / "DB_CLEANUP_9_0_12_REPORT.md"

REFAC_SYSTEMS = [
    "systems/character_system.py",
    "systems/player_system.py",
    "systems/contract_system.py",
    "systems/energy_system.py",
    "systems/regen_system.py",
    "systems/equipment_system.py",
    "systems/refine_system.py",
    "systems/guild_system.py",
    "systems/auction_house_system.py",
]

DATA_MODULES = [
    "data/classes.py",
    "data/equipment_profiles.py",
    "data/balance.py",
]


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def parse_defs(text: str):
    tree = ast.parse(text)
    results = []

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            results.append({
                "name": node.name,
                "lineno": node.lineno,
                "end_lineno": getattr(node, "end_lineno", node.lineno),
                "kind": "async def" if isinstance(node, ast.AsyncFunctionDef) else "def",
            })
        elif isinstance(node, ast.ClassDef):
            results.append({
                "name": node.name,
                "lineno": node.lineno,
                "end_lineno": getattr(node, "end_lineno", node.lineno),
                "kind": "class",
            })

    return results


def duplicate_defs(defs):
    by_name = defaultdict(list)
    for row in defs:
        by_name[row["name"]].append(row)
    return {name: rows for name, rows in by_name.items() if len(rows) > 1}


def legacy_refs(text: str):
    pattern = re.compile(r"_legacy_[A-Za-z0-9_]+")
    found = sorted(set(pattern.findall(text)))
    by_func = defaultdict(list)

    for legacy_name in found:
        inferred = legacy_name

        for prefix in [
            "_legacy_regen_v1_",
            "_legacy_equipment_ro_v1_",
            "_legacy_equipment_write_v1_",
            "_legacy_equipment_rds_v1_",
            "_legacy_",
        ]:
            if inferred.startswith(prefix):
                inferred = inferred[len(prefix):]
                break

        for suffix in [
            "_before_character_system_v1",
            "_before_player_system_v1",
            "_before_contract_system_v1",
            "_before_energy_system_v1",
        ]:
            if inferred.endswith(suffix):
                inferred = inferred[:-len(suffix)]

        by_func[inferred].append(legacy_name)

    return found, by_func


def facade_markers(text: str):
    markers = []
    for i, line in enumerate(text.splitlines(), start=1):
        if "REFACTOR 9.0" in line or "ROM 9.0" in line or "COMPATIBILITY" in line:
            if line.strip().startswith("#"):
                markers.append((i, line.strip()))
    return markers


def module_status(paths):
    rows = []
    for rel in paths:
        path = ROOT / rel
        rows.append((rel, path.exists(), path.stat().st_size if path.exists() else 0))
    return rows


def build_report():
    if not DB_PATH.exists():
        raise SystemExit("db.py not found")

    text = read_text(DB_PATH)
    defs = parse_defs(text)
    duplicates = duplicate_defs(defs)
    legacy_names, legacy_by_func = legacy_refs(text)
    markers = facade_markers(text)
    systems = module_status(REFAC_SYSTEMS)
    data_modules = module_status(DATA_MODULES)

    unsafe_delete = []
    maybe_cleanup_later = []

    for name, rows in duplicates.items():
        if name in legacy_by_func:
            unsafe_delete.append((name, rows, legacy_by_func[name]))
        else:
            maybe_cleanup_later.append((name, rows))

    lines = []
    lines.append("# DB Cleanup 9.0.12 Readiness Report")
    lines.append("")
    lines.append("This report was generated by `tools/db_cleanup_readiness.py`.")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Top-level definitions in `db.py`: **{len(defs)}**")
    lines.append(f"- Duplicate definition names: **{len(duplicates)}**")
    lines.append(f"- Legacy reference variables detected: **{len(legacy_names)}**")
    lines.append(f"- Duplicate functions currently unsafe to delete because compatibility wrappers still reference legacy implementations: **{len(unsafe_delete)}**")
    lines.append(f"- Duplicate functions that may be cleanup candidates later: **{len(maybe_cleanup_later)}**")
    lines.append("")

    lines.append("## Refactor modules status")
    lines.append("")
    for rel, exists, size in systems:
        status = "OK" if exists else "MISSING"
        lines.append(f"- `{rel}` — **{status}** ({size} bytes)")
    lines.append("")

    lines.append("## Data modules status")
    lines.append("")
    for rel, exists, size in data_modules:
        status = "OK" if exists else "MISSING"
        lines.append(f"- `{rel}` — **{status}** ({size} bytes)")
    lines.append("")

    lines.append("## Facade / compatibility markers found in db.py")
    lines.append("")
    if markers:
        for lineno, marker in markers[-80:]:
            lines.append(f"- line {lineno}: `{marker}`")
    else:
        lines.append("No markers found.")
    lines.append("")

    lines.append("## Duplicate definitions")
    lines.append("")
    if duplicates:
        for name, rows in sorted(duplicates.items()):
            places = ", ".join(f"{row['kind']}@{row['lineno']}" for row in rows)
            lines.append(f"- `{name}`: {places}")
    else:
        lines.append("No duplicates found.")
    lines.append("")

    lines.append("## Unsafe-to-delete duplicates right now")
    lines.append("")
    lines.append("These names are still referenced by `_legacy_*` compatibility variables. Do **not** delete old implementations yet unless the target system has a real implementation and no longer calls legacy.")
    lines.append("")
    if unsafe_delete:
        for name, rows, refs in sorted(unsafe_delete, key=lambda x: x[0]):
            places = ", ".join(f"line {row['lineno']}" for row in rows)
            ref_text = ", ".join(refs[:6])
            if len(refs) > 6:
                ref_text += f", ... +{len(refs) - 6}"
            lines.append(f"- `{name}` ({places}) — refs: `{ref_text}`")
    else:
        lines.append("None detected.")
    lines.append("")

    lines.append("## Possible later cleanup candidates")
    lines.append("")
    lines.append("These duplicates did not match a detected `_legacy_*` reference. They still require manual review before deletion.")
    lines.append("")
    if maybe_cleanup_later:
        for name, rows in sorted(maybe_cleanup_later, key=lambda x: x[0]):
            places = ", ".join(f"line {row['lineno']}" for row in rows)
            lines.append(f"- `{name}` ({places})")
    else:
        lines.append("None detected.")
    lines.append("")

    lines.append("## Recommended next steps")
    lines.append("")
    lines.append("1. Do **not** mass-delete old `db.py` implementations yet. Most 9.0 systems are compatibility facades that still call legacy implementations.")
    lines.append("2. Convert each system from legacy delegation to real implementation one domain at a time.")
    lines.append("3. After a system no longer calls `_legacy_*`, remove the corresponding old `db.py` implementations and keep only facade wrappers.")
    lines.append("4. Run checks after each cleanup:")
    lines.append("")
    lines.append("```powershell")
    lines.append("python -m py_compile .\\db.py")
    lines.append("python tools/check_imports.py")
    lines.append("python tools/smoke_test_rom_core.py")
    lines.append("python tools/db_cleanup_readiness.py")
    lines.append("```")
    lines.append("")

    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    return {
        "definitions": len(defs),
        "duplicates": len(duplicates),
        "legacy_refs": len(legacy_names),
        "unsafe_delete": len(unsafe_delete),
        "maybe_cleanup_later": len(maybe_cleanup_later),
        "report": str(REPORT_PATH),
    }


def main():
    result = build_report()
    print("DB cleanup 9.0.12 readiness")
    print("============================")
    for key, value in result.items():
        print(f"{key}: {value}")


if __name__ == "__main__":
    main()
'''


def make_backup(root, target):
    backup_dir = root / "backup"
    backup_dir.mkdir(exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = str(target.relative_to(root)).replace("\\", "_").replace("/", "_")
    backup_path = backup_dir / f"{safe_name}_{PATCH_NAME}_{timestamp}.bak"
    backup_path.write_text(target.read_text(encoding="utf-8"), encoding="utf-8")
    return backup_path


def main():
    root = Path(__file__).resolve().parents[1]
    target = root / TARGET_RELATIVE

    if not target.exists():
        raise SystemExit(f"❌ Не знайдено файл: {target}")

    backup = make_backup(root, target)
    target.write_text(TOOL_CODE, encoding="utf-8")

    try:
        py_compile.compile(str(target), doraise=True)
    except Exception as error:
        raise SystemExit(
            "❌ Помилка компіляції tools/db_cleanup_readiness.py після фікса.\n"
            f"Backup: {backup}\n\n"
            f"Помилка:\n{error}"
        )

    print("✅ Патч 9.0.12a fix db_cleanup_readiness.py застосовано успішно.")
    print(f"✅ Backup: {backup}")
    print("✅ tools/db_cleanup_readiness.py пройшов py_compile.")
    print("")
    print("Тепер запусти:")
    print("python tools/db_cleanup_readiness.py")
    print("python tools/check_imports.py")
    print("python tools/smoke_test_rom_core.py")
    print("")
    print("Після запуску має створитися DB_CLEANUP_9_0_12_REPORT.md")


if __name__ == "__main__":
    main()
