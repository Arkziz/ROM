from pathlib import Path
from datetime import datetime
import ast
import py_compile


PATCH_NAME = "9_0_10a_data_balance_extract_fixed"


BALANCE_PREFIXES = (
    "CONTRACT_",
    "CONTRACTS_",
    "DAILY_",
    "ENERGY_",
    "HP_REGEN_",
    "MP_REGEN_",
    "REGEN_",
    "RARITY_",
    "REPAIR_",
    "SELL_",
    "GUILD_",
    "AUCTION_",
    "REFINE_",
    "BLACKSMITH_",
    "SHOP_",
    "LOOT_",
    "DROP_",
    "EXP_",
)

BALANCE_EXACT_NAMES = {
    "CONTRACT_MOBS_EQUIVALENT",
    "CONTRACTS_UNLOCK_LEVEL",
    "DAILY_CONTRACT_LIMIT",
    "CONTRACT_TARGET_KILLS",
    "ENERGY_MAX",
    "ENERGY_REGEN_MINUTES",
    "HP_REGEN_PERCENT",
    "HP_REGEN_MINUTES",
    "MAX_INVENTORY_SLOTS",
    "BASE_MAX_HP",
    "BASE_MAX_MP",
}


def make_backup(root, target):
    backup_dir = root / "backup"
    backup_dir.mkdir(exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = str(target.relative_to(root)).replace("\\", "_").replace("/", "_")
    backup_path = backup_dir / f"{safe_name}_{PATCH_NAME}_{timestamp}.bak"

    backup_path.write_text(
        target.read_text(encoding="utf-8"),
        encoding="utf-8"
    )

    return backup_path


def is_balance_constant(name):
    if not name.isupper():
        return False

    if name in BALANCE_EXACT_NAMES:
        return True

    return any(name.startswith(prefix) for prefix in BALANCE_PREFIXES)


def collect_balance_constants(db_path):
    text = db_path.read_text(encoding="utf-8")
    tree = ast.parse(text)

    constants = {}

    for node in tree.body:
        target_name = None
        value_node = None

        if isinstance(node, ast.Assign):
            if len(node.targets) != 1:
                continue

            target = node.targets[0]

            if isinstance(target, ast.Name):
                target_name = target.id
                value_node = node.value

        elif isinstance(node, ast.AnnAssign):
            if isinstance(node.target, ast.Name):
                target_name = node.target.id
                value_node = node.value

        if not target_name or value_node is None:
            continue

        if not is_balance_constant(target_name):
            continue

        try:
            value = ast.literal_eval(value_node)
        except Exception:
            continue

        constants[target_name] = value

    return constants


def write_balance_file(root, constants):
    data_dir = root / "data"
    data_dir.mkdir(exist_ok=True)

    init_path = data_dir / "__init__.py"

    if not init_path.exists():
        init_path.write_text(
            '"""Static data package for ROM."""\n',
            encoding="utf-8"
        )

    balance_path = data_dir / "balance.py"

    if balance_path.exists():
        make_backup(root, balance_path)

    lines = []
    lines.append('"""')
    lines.append("ROM balance constants.")
    lines.append("")
    lines.append("Generated by patch 9.0.10a.")
    lines.append("")
    lines.append("Important:")
    lines.append("- This file stores static gameplay balance values.")
    lines.append("- db.py remains compatibility facade for now.")
    lines.append("- Old constants in db.py are not removed yet.")
    lines.append('"""')
    lines.append("")
    lines.append("# ==============================")
    lines.append("# ✅ EXTRACTED BALANCE CONSTANTS")
    lines.append("# ==============================")
    lines.append("")

    for name in sorted(constants):
        lines.append(f"{name} = {repr(constants[name])}")

    lines.append("")
    lines.append("")
    lines.append("def get_balance_constant(name, default=None):")
    lines.append("    return globals().get(name, default)")
    lines.append("")
    lines.append("")
    lines.append("__all__ = [")
    for name in sorted(constants):
        lines.append(f"    {name!r},")
    lines.append("    'get_balance_constant',")
    lines.append("]")
    lines.append("")

    balance_path.write_text("\n".join(lines), encoding="utf-8")

    return balance_path, init_path


def patch_db_compat_import(root, constants):
    db_path = root / "db.py"

    text = db_path.read_text(encoding="utf-8")
    marker = "# ✅ DATA BALANCE COMPATIBILITY FACADE V1"

    if marker in text:
        print("ℹ️ db.py: balance compatibility block already exists.")
        return None

    backup_path = make_backup(root, db_path)

    names = sorted(constants)

    if names:
        import_lines = []
        import_lines.append("")
        import_lines.append("")
        import_lines.append("# ==============================")
        import_lines.append("# ✅ DATA BALANCE COMPATIBILITY FACADE V1")
        import_lines.append("# ==============================")
        import_lines.append("")
        import_lines.append("try:")
        import_lines.append("    from data.balance import (")
        for name in names:
            import_lines.append(f"        {name},")
        import_lines.append("        get_balance_constant,")
        import_lines.append("    )")
        import_lines.append("except Exception:")
        import_lines.append("    pass")
        import_lines.append("")
    else:
        import_lines = []
        import_lines.append("")
        import_lines.append("")
        import_lines.append("# ==============================")
        import_lines.append("# ✅ DATA BALANCE COMPATIBILITY FACADE V1")
        import_lines.append("# ==============================")
        import_lines.append("")
        import_lines.append("try:")
        import_lines.append("    from data.balance import get_balance_constant")
        import_lines.append("except Exception:")
        import_lines.append("    pass")
        import_lines.append("")

    text = text.rstrip() + "\n" + "\n".join(import_lines)

    db_path.write_text(text, encoding="utf-8")

    return backup_path


def patch_check_imports(root):
    target = root / "tools" / "check_imports.py"

    if not target.exists():
        print("⚠️ tools/check_imports.py not found, skipping.")
        return None

    text = target.read_text(encoding="utf-8")
    original = text
    backup_path = make_backup(root, target)

    if '"data/balance.py"' not in text and "'data/balance.py'" not in text:
        text = text.replace(
            '"systems/auction_house_system.py",',
            '"systems/auction_house_system.py",\n    "data/balance.py",'
        )

    if '"data.balance"' not in text and "'data.balance'" not in text:
        text = text.replace(
            '"systems.auction_house_system",',
            '"systems.auction_house_system",\n    "data.balance",'
        )

    if text != original:
        target.write_text(text, encoding="utf-8")
        return backup_path

    return None


def main():
    root = Path(__file__).resolve().parents[1]
    db_path = root / "db.py"

    if not db_path.exists():
        raise SystemExit("❌ db.py не знайдено.")

    constants = collect_balance_constants(db_path)

    balance_path, init_path = write_balance_file(root, constants)
    db_backup = patch_db_compat_import(root, constants)
    tools_backup = patch_check_imports(root)

    try:
        py_compile.compile(str(balance_path), doraise=True)
        py_compile.compile(str(init_path), doraise=True)
        py_compile.compile(str(db_path), doraise=True)

        check_imports_path = root / "tools" / "check_imports.py"

        if check_imports_path.exists():
            py_compile.compile(str(check_imports_path), doraise=True)

    except Exception as error:
        raise SystemExit(
            "❌ Помилка компіляції після patch_9_0_10a.\n"
            f"Помилка:\n{error}"
        )

    print("✅ Патч 9.0.10a Data Balance Extract FIXED застосовано успішно.")
    print("")
    print("Створено/оновлено:")
    print(f"- {balance_path}")
    print(f"- {init_path}")
    print("- db.py compatibility facade")
    print("- tools/check_imports.py")
    print("")
    print(f"Витягнуто balance-констант: {len(constants)}")

    if constants:
        print("Приклади:")
        for name in sorted(constants)[:20]:
            print(f"- {name}")

        if len(constants) > 20:
            print(f"... ще {len(constants) - 20}")

    print("")
    print("Backup:")

    if db_backup:
        print(f"- {db_backup}")

    if tools_backup:
        print(f"- {tools_backup}")

    print("")
    print("Після патча запусти:")
    print("python -m py_compile .\\data\\balance.py")
    print("python -m py_compile .\\db.py")
    print("python tools/check_imports.py")
    print("python tools/smoke_test_rom_core.py")


if __name__ == "__main__":
    main()