from pathlib import Path
from datetime import datetime
import ast
import py_compile

PATCH_NAME = "9_0_6_equipment_system_readonly_extract"
MARKER = "# ✅ REFACTOR 9.0.6: EQUIPMENT SYSTEM READONLY FACADE"

READONLY_FUNCTION_CANDIDATES = [
    # equipment slots / equipped reads
    "ensure_equipment_slots",
    "get_all_equipped_items",
    "get_equipped_items",
    "get_equipped_item",
    "get_equipped_item_by_slot",
    "get_equipment_slot_inventory_id",
    "get_equipped_items_for_repair",

    # item/inventory lookup helpers used by UI, combat, auction, repair
    "get_inventory_detailed",
    "get_inventory_entry",
    "get_item_by_inventory_id",
    "get_item_by_inventory_id_full",
    "get_item_bonuses",
    "get_equipped_item_defenses",
    "get_sellable_equipment_items",

    # weapon damage read-only helpers
    "init_weapon_damage_system",
    "calculate_weapon_damage_by_values",
    "get_weapon_damage_by_inventory_id",
    "get_inventory_weapon_damage_display",

    # refine display / item display helpers, if present
    "get_inventory_refine_level",
    "get_inventory_refined_display_name",
    "get_refine_display_suffix",
    "format_refined_item_name",

    # class/equipment compatibility read-only helpers, if present
    "can_equip_item_by_class",
    "can_equip_inventory_item_by_class",
    "is_inventory_item_class_compatible",
    "get_item_allowed_classes_text",
    "get_item_allowed_classes",
]

EQUIPMENT_SYSTEM_CODE = '''"""
ROM Equipment System — Read-only Facade
=======================================

Refactor 9.0.6 compatibility module.

Scope of this step:
- read-only equipment/inventory/equipped-item helpers;
- weapon damage read-only helpers;
- compatibility read-only helpers, if they exist in db.py.

Not included yet:
- equip/unequip write actions;
- repair write actions;
- durability write actions;
- sell/write economy actions.

This stage is intentionally conservative:
- db.py remains the public compatibility facade for handlers;
- legacy implementations are kept in db.py as _legacy_equipment_ro_v1_* references;
- this module delegates to those legacy implementations.
"""


def _db():
    import db
    return db


def _call_legacy(name, *args, **kwargs):
    db = _db()
    legacy_name = f"_legacy_equipment_ro_v1_{name}"
    legacy = getattr(db, legacy_name, None)

    if legacy is None:
        raise AttributeError(f"Legacy equipment read-only function not found: {legacy_name}")

    return legacy(*args, **kwargs)


# The concrete functions are generated by the patch below.
'''


def make_backup(root, target):
    backup_dir = root / "backup"
    backup_dir.mkdir(exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = str(target.relative_to(root)).replace("\\", "_").replace("/", "_")
    backup_path = backup_dir / f"{safe_name}_{PATCH_NAME}_{timestamp}.bak"
    backup_path.write_text(target.read_text(encoding="utf-8"), encoding="utf-8")
    return backup_path


def get_defined_functions(text):
    tree = ast.parse(text)
    result = []
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            result.append(node.name)
    return result


def build_equipment_system_code(found_names):
    lines = [EQUIPMENT_SYSTEM_CODE.rstrip(), "", ""]
    for name in found_names:
        lines.append(f"def {name}(*args, **kwargs):")
        lines.append(f"    return _call_legacy('{name}', *args, **kwargs)")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_equipment_system(root, found_names):
    systems_dir = root / "systems"
    systems_dir.mkdir(exist_ok=True)
    target = systems_dir / "equipment_system.py"

    backup = None
    if target.exists():
        backup = make_backup(root, target)

    target.write_text(build_equipment_system_code(found_names), encoding="utf-8")
    return target, backup


def patch_db(root, found_names):
    target = root / "db.py"
    if not target.exists():
        raise SystemExit("❌ db.py не знайдено.")

    original = target.read_text(encoding="utf-8")
    if MARKER in original:
        print("ℹ️ db.py вже має REFACTOR 9.0.6 block. Пропускаю db.py.")
        return None, original

    backup = make_backup(root, target)

    lines = []
    lines.append("")
    lines.append(MARKER)
    lines.append("# This block keeps db.py as public compatibility facade.")
    lines.append("# Actual read-only domain entrypoint: systems/equipment_system.py")
    lines.append("")
    lines.append("def _equipment_system_ro_v1():")
    lines.append("    from systems import equipment_system")
    lines.append("    return equipment_system")
    lines.append("")

    for name in found_names:
        legacy_name = f"_legacy_equipment_ro_v1_{name}"
        lines.append("try:")
        lines.append(f"    {legacy_name}")
        lines.append("except NameError:")
        lines.append(f"    {legacy_name} = {name}")
        lines.append("")

    for name in found_names:
        lines.append(f"def {name}(*args, **kwargs):")
        lines.append(f"    return _equipment_system_ro_v1().{name}(*args, **kwargs)")
        lines.append("")

    patched = original.rstrip() + "\n" + "\n".join(lines) + "\n"
    target.write_text(patched, encoding="utf-8")
    return backup, original


def patch_tools_check_imports(root):
    target = root / "tools" / "check_imports.py"
    if not target.exists():
        return None

    text = target.read_text(encoding="utf-8")
    changed = False

    if '"systems/equipment_system.py"' not in text and "'systems/equipment_system.py'" not in text:
        marker = '"systems/regen_system.py",'
        if marker in text:
            text = text.replace(marker, marker + '\n    "systems/equipment_system.py",')
            changed = True
        else:
            marker = '"systems/refine_system.py",'
            if marker in text:
                text = text.replace(marker, marker + '\n    "systems/equipment_system.py",')
                changed = True

    if '"systems.equipment_system"' not in text and "'systems.equipment_system'" not in text:
        marker = '"systems.regen_system",'
        if marker in text:
            text = text.replace(marker, marker + '\n    "systems.equipment_system",')
            changed = True
        else:
            marker = '"systems.refine_system",'
            if marker in text:
                text = text.replace(marker, marker + '\n    "systems.equipment_system",')
                changed = True

    if changed:
        backup = make_backup(root, target)
        target.write_text(text, encoding="utf-8")
        return backup

    return None


def main():
    root = Path(__file__).resolve().parents[1]
    db_path = root / "db.py"

    if not db_path.exists():
        raise SystemExit("❌ db.py не знайдено.")

    db_original = db_path.read_text(encoding="utf-8")
    defined = set(get_defined_functions(db_original))
    found_names = [name for name in READONLY_FUNCTION_CANDIDATES if name in defined]

    if not found_names:
        raise SystemExit("❌ Не знайдено read-only equipment-функцій у db.py для wrapper-ів.")

    equipment_path = root / "systems" / "equipment_system.py"
    equipment_original = equipment_path.read_text(encoding="utf-8") if equipment_path.exists() else None

    changed_files = []
    backups = []

    try:
        equipment_path, equipment_backup = write_equipment_system(root, found_names)
        changed_files.append(equipment_path)
        if equipment_backup:
            backups.append(equipment_backup)

        db_backup, _ = patch_db(root, found_names)
        if db_backup:
            backups.append(db_backup)
            changed_files.append(db_path)

        tools_backup = patch_tools_check_imports(root)
        if tools_backup:
            backups.append(tools_backup)
            changed_files.append(root / "tools" / "check_imports.py")

        py_compile.compile(str(equipment_path), doraise=True)
        py_compile.compile(str(db_path), doraise=True)
        if (root / "tools" / "check_imports.py").exists():
            py_compile.compile(str(root / "tools" / "check_imports.py"), doraise=True)

    except Exception as error:
        db_path.write_text(db_original, encoding="utf-8")
        if equipment_original is None:
            if equipment_path.exists():
                equipment_path.unlink()
        else:
            equipment_path.write_text(equipment_original, encoding="utf-8")
        raise SystemExit(
            "❌ Помилка під час patch_9_0_6_equipment_system_readonly_extract.\n"
            "db.py і systems/equipment_system.py відновлено.\n\n"
            f"Помилка:\n{error}"
        )

    print("✅ Патч 9.0.6 Equipment System Read-only Extract застосовано успішно.")
    print()
    print("Створено/оновлено:")
    for path in changed_files:
        print(f"- {path}")

    if backups:
        print()
        print("Backup:")
        for path in backups:
            print(f"- {path}")

    print()
    print("Read-only equipment API перенесено у facade:")
    for name in found_names:
        print(f"- {name}")

    print()
    print("Що зроблено:")
    print("- створено systems/equipment_system.py")
    print("- db.py отримав compatibility wrappers для equipment read-only API")
    print("- старі реалізації db.py збережені як _legacy_equipment_ro_v1_* refs")
    print("- equip/unequip/repair/durability WRITE-логіку ще НЕ переносили")
    print("- tools/check_imports.py оновлено для systems.equipment_system, якщо можливо")
    print()
    print("Після патча запусти:")
    print("python -m py_compile .\\systems\\equipment_system.py")
    print("python -m py_compile .\\db.py")
    print("python tools/check_imports.py")
    print("python tools/smoke_test_rom_core.py")


if __name__ == "__main__":
    main()
