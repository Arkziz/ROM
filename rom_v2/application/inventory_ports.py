"""Application ports for the audited inventory service."""
from __future__ import annotations
from typing import Protocol, Sequence
from rom_v2.domain.item import ItemDefinition, ItemInstance

class InventoryRepositoryPort(Protocol):
    def get_definition(self,item_id:int)->ItemDefinition|None: ...
    def list_by_owner(self,owner_user_id:int)->Sequence[ItemInstance]: ...
    def get_instance(self,owner_user_id:int,inventory_id:int)->ItemInstance|None: ...
    def insert_instance(self,owner_user_id:int,item_id:int,quantity:int)->ItemInstance: ...
    def change_quantity(self,inventory_id:int,quantity:int)->None: ...
    def delete_instance(self,inventory_id:int)->None: ...

class InventoryReservationReaderPort(Protocol):
    def reserved_quantity(self,owner_user_id:int,inventory_id:int)->int: ...

class InventoryUnitOfWorkPort(Protocol):
    inventory: InventoryRepositoryPort
    def __enter__(self)->"InventoryUnitOfWorkPort": ...
    def __exit__(self,exc_type,exc,tb)->None: ...
    def commit(self)->None: ...
    def rollback(self)->None: ...

class InventoryUnitOfWorkFactoryPort(Protocol):
    def __call__(self)->InventoryUnitOfWorkPort: ...
