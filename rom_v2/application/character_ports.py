"""Application ports for V1-faithful character lifecycle persistence."""
from __future__ import annotations
from typing import Protocol
from rom_v2.domain.character import Character
class CharacterRepositoryPort(Protocol):
 def find_by_id(self,character_id:str)->Character|None:...
 def find_by_account_id(self,account_id:str)->Character|None:...
 def find_by_name_key(self,name_key:str)->Character|None:...
 def add(self,character:Character)->None:...
 def delete(self,character_id:str)->None:...
class CharacterUnitOfWorkPort(Protocol):
 characters:CharacterRepositoryPort
 def __enter__(self)->CharacterUnitOfWorkPort:...
 def __exit__(self,exception_type,exception,traceback)->bool:...
 def commit(self)->None:...
class CharacterUnitOfWorkFactoryPort(Protocol):
 def __call__(self)->CharacterUnitOfWorkPort:...
