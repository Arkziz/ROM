"""Application ports for primary-stat state persistence."""
from __future__ import annotations
from typing import Protocol
from rom_v2.domain.primary_stats import AttributePointState
class PrimaryStatRepositoryPort(Protocol):
 def find(self,character_id:str)->AttributePointState|None:...
 def add(self,character_id:str,state:AttributePointState)->None:...
 def replace(self,character_id:str,state:AttributePointState,expected_free_points:int)->None:...
class PrimaryStatUnitOfWorkPort(Protocol):
 primary_stats:PrimaryStatRepositoryPort
 def __enter__(self)->PrimaryStatUnitOfWorkPort:...
 def __exit__(self,exception_type,exception,traceback)->bool:...
 def commit(self)->None:...
class PrimaryStatUnitOfWorkFactoryPort(Protocol):
 def __call__(self)->PrimaryStatUnitOfWorkPort:...
