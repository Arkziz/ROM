"""Application ports for persistent character resources."""
from __future__ import annotations
from typing import Protocol
from rom_v2.domain.resource_lifecycle import ResourceState
class ResourceRepositoryPort(Protocol):
    def get(self,character_id:str,max_hp:int,max_mp:int)->ResourceState|None:...
    def save_current(self,character_id:str,state:ResourceState)->None:...
class ResourceUnitOfWorkPort(Protocol):
    resources:ResourceRepositoryPort
    def __enter__(self)->ResourceUnitOfWorkPort:...
    def commit(self)->None:...
    def __exit__(self,exception_type,exception,traceback)->bool:...
class ResourceUnitOfWorkFactoryPort(Protocol):
    def __call__(self)->ResourceUnitOfWorkPort:...
