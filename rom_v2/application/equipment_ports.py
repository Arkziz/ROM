"""Application ports for atomic equipment-slot persistence."""
from __future__ import annotations
from typing import Protocol,Sequence
from rom_v2.domain.equipment import EquipmentSlot
from rom_v2.domain.item import ItemInstance
class EquipmentRepositoryPort(Protocol):
 def list_slots(self,owner_user_id:int)->Sequence[EquipmentSlot]: ...
 def get_inventory_instance(self,owner_user_id:int,inventory_id:int)->ItemInstance|None: ...
 def set_slot(self,owner_user_id:int,slot_key:str,inventory_id:int)->None: ...
 def clear_slot(self,owner_user_id:int,slot_key:str)->None: ...
class EquipmentUnitOfWorkPort(Protocol):
 equipment:EquipmentRepositoryPort
 def __enter__(self)->"EquipmentUnitOfWorkPort": ...
 def __exit__(self,exc_type,exc,tb)->None: ...
 def commit(self)->None: ...
 def rollback(self)->None: ...
class EquipmentUnitOfWorkFactoryPort(Protocol):
 def __call__(self)->EquipmentUnitOfWorkPort: ...
